-- =============================================================================
-- Attach the audit trigger to every table in the business schemas, except
-- high-volume / derived tables.
-- =============================================================================
DO $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT schemaname, tablename FROM pg_tables
        WHERE schemaname IN ('core','auth','hr','payroll')
          AND (schemaname, tablename) NOT IN (
              ('core','schema_migrations'), ('core','doc_sequences'),
              ('auth','refresh_tokens'), ('auth','password_reset_tokens'),
              ('hr','employee_attendances'), ('hr','leave_credit_run_employees'),
              ('payroll','payroll_details'), ('payroll','payroll_period_leave_postings'),
              ('payroll','pf_contribution_events'))
    LOOP
        EXECUTE format('CREATE TRIGGER trg_audit AFTER INSERT OR UPDATE OR DELETE ON %I.%I
                        FOR EACH ROW EXECUTE FUNCTION audit.log_row_change()', r.schemaname, r.tablename);
    END LOOP;
END $$;

