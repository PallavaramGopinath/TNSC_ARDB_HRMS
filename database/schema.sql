-- Generic row-change trigger. The API sets per transaction:
--   SET LOCAL app.user_id = '…'; SET LOCAL app.user_name = '…'; SET LOCAL app.correlation_id = '…';
CREATE OR REPLACE FUNCTION audit.log_row_change() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
    v_old  jsonb;
    v_new  jsonb;
    v_diff jsonb := '{}'::jsonb;
    v_key  text;
    v_mask text[];
BEGIN
    SELECT coalesce(array_agg(column_name), '{}') INTO v_mask FROM audit.masked_columns;

    IF TG_OP IN ('UPDATE','DELETE') THEN v_old := to_jsonb(OLD); END IF;
    IF TG_OP IN ('UPDATE','INSERT') THEN v_new := to_jsonb(NEW); END IF;

    IF TG_OP = 'UPDATE' THEN
        FOR v_key IN SELECT jsonb_object_keys(v_new) LOOP
            IF v_new -> v_key IS DISTINCT FROM v_old -> v_key THEN
                v_diff := v_diff || jsonb_build_object(v_key,
                    CASE WHEN v_key = ANY(v_mask)
                         THEN jsonb_build_object('old','***','new','***')
                         ELSE jsonb_build_object('old', v_old -> v_key, 'new', v_new -> v_key) END);
            END IF;
        END LOOP;
        IF v_diff = '{}'::jsonb THEN RETURN NEW; END IF;  -- no real change
    ELSE
        v_diff := coalesce(v_new, v_old);
        FOREACH v_key IN ARRAY v_mask LOOP
            IF v_diff ? v_key THEN v_diff := jsonb_set(v_diff, ARRAY[v_key], '"***"'); END IF;
        END LOOP;
    END IF;

    INSERT INTO audit.row_changes(schema_name, table_name, operation, row_pk, changes,
                                  user_id, user_name, correlation_id)
    VALUES (TG_TABLE_SCHEMA, TG_TABLE_NAME, TG_OP,
            coalesce(v_new, v_old) ->> 'id',
            v_diff,
            nullif(current_setting('app.user_id', true), ''),
            nullif(current_setting('app.user_name', true), ''),
            nullif(current_setting('app.correlation_id', true), ''));

    RETURN coalesce(NEW, OLD);
END $$;

