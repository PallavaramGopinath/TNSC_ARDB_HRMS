-- =============================================================================
-- TNSC ARDB — HR & Payroll baseline schema
-- Ported from TNCU_GAMS (EF Core / PostgreSQL). See docs/tncu-gams-extraction.md.
--
-- Schemas:  core    shared masters (branches, places, FY, settings, menu, numbering)
--           auth    users, module grants, refresh tokens
--           audit   row-change trail + security/approval events
--           hr      employee lifecycle
--           payroll pay computation
--           epf     reserved for the EPF Trust module (empty)
--
-- Conventions: snake_case; identity PKs; enums are varchar + CHECK; money numeric(14,2)/(16,2);
-- rates numeric(8,2); business dates `date`; stamps `timestamptz` (UTC).
-- Accounting columns from TNCU (ledger_id, voucher_id, …) are intentionally dropped (ARDB D1).
-- Idempotent only on an empty database: run once, then use numbered migrations.
-- =============================================================================

